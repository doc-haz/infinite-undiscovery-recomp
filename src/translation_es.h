// Strong override of the message directory parser.
extern "C" void __imp__sub_826D52C0(PPCContext& ctx, uint8_t* base);
extern "C" void sub_826D52C0(PPCContext& ctx, uint8_t* base) {
  const uint32_t obj = ctx.r3.u32;  // capture BEFORE: on return, r3 = return value
  __imp__sub_826D52C0(ctx, base);
  iu::translation::ZoneNamesStart(base);
  iu::translation::LoadCatalog();
  iu::translation::TrySubstitute(base, obj);
  // Persistent textures by SIGNATURE (UI atlas, GAME OVER, Now Loading, Reload...).
  // `Tick` starts (once) the THREAD that searches for them; the game is not blocked.
  static const bool want_scan = []() {
    // Priority: CVAR > environment > wizard > default (enabled).
    if (rex::cvar::GetFlagSource("es_textures") != rex::cvar::Source::kDefault)
      return iu::tr::ParseBool(rex::cvar::GetFlagByName("es_textures"), true);
    const char* e = std::getenv("IU_ES_SCAN");
    if (e && e[0]) return e[0] != '0';
    return iu::portable::EsTextures();
  }();
  if (want_scan) iu::ui::Tick(base);
}
