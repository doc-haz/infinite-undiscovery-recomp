// translation_es.h -- ES TRANSLATION HOOK (F5) for Infinite Undiscovery (recomp).
//
// Mechanism: ReXGlue uses weak aliases.  We replace (strong symbol) the message
// directory parser `sub_826D52C0`, call the original via
// `__imp__sub_826D52C0` and, if the message (bank,id) has a translation, replace
// the resolved text pointer (`obj+0x78`) with our own buffer in guest memory
// holding the already-encoded ES codes (scheme b0/b1; see docs/re/font-loader.md).
//
// The bank is identified by the SIGNATURE of the loaded `.msg` header
// (`total,count,atlas_w,atlas_h`), which the parser has in `obj+0x64`.
//
// CATALOG: `translation/es_catalog.bin` (generated by tools/gen_es_catalog.py):
//   u32 magic 'IUC1', u32 n, and n blocks:
//     u32 total,count,atlas_w,atlas_h,id,ncodes ; u16 codes[ncodes]
//
// Include ONCE only from src/main.cpp.

